#!/usr/bin/env bash
# =============================================================================
# Dar Nginx site - generate the production vhost (idempotent)
# =============================================================================
# Purpose : write /etc/nginx/sites-available/dar-elemam-hafs from the canonical
#           template in this script, enable it, validate nginx -t and reload.
# Requires: root, or the deploy user with passwordless sudo.
#           deploy/.env with DAR_DOMAIN (or pass --domain).
# Usage   : sudo bash deploy/setup-nginx.sh [--domain HOST] [--skip-smoke]
# Behaviour:
#   * If the Let's Encrypt certificate already exists, the full TLS server block
#     is written with the Certbot-managed certificate lines preserved.
#   * If there is no certificate yet, an HTTP-only block is written so Certbot
#     can complete the HTTP challenge; run certbot afterwards (printed hint).
#   * Security headers are added at the Nginx layer: HSTS (TLS only),
#     X-Content-Type-Options, Referrer-Policy, X-Frame-Options, Permissions-Policy.
# Safe    : the current site file is copied to /var/backups/dar-config/<stamp>/
#           first, and the backup is restored if nginx -t fails.
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="${DAR_REPO_DIR:-$(cd -- "$SCRIPT_DIR/.." && pwd)}"
if [ ! -f "$REPO_DIR/deploy/.env" ] && [ -f /opt/dar/deploy/.env ]; then
  REPO_DIR=/opt/dar
fi
ENV_FILE="$REPO_DIR/deploy/.env"
SITE_NAME="dar-elemam-hafs"
SITE_FILE="/etc/nginx/sites-available/$SITE_NAME"
SITE_LINK="/etc/nginx/sites-enabled/$SITE_NAME"
CERT_ROOT="/etc/letsencrypt/live"
BACKUP_STAMP="$(date +%Y%m%d-%H%M%S)"
CONFIG_BACKUP_DIR="/var/backups/dar-config/$BACKUP_STAMP"
DOMAIN=""
SKIP_SMOKE=0
REAL_IP_MODE=${DAR_REAL_IP_MODE:-cloudflare}

usage() {
  cat <<'USAGE'
Usage: setup-nginx.sh [--domain HOST] [--skip-smoke] [--real-ip-mode direct|cloudflare]

  --domain HOST  Domain to configure (default: DAR_DOMAIN from deploy/.env).
  --skip-smoke   Skip the local health/SPA smoke requests after reload.
  --real-ip-mode cloudflare|direct  Default from DAR_REAL_IP_MODE (cloudflare). cloudflare installs
                 deploy/nginx/cloudflare-realip.conf (CF ranges + CF-Connecting-IP) so nginx's
                 $remote_addr is the real client; direct trusts no proxy header.
  --help         Show this help.
USAGE
}

while [ "$#" -gt 0 ]; do
  case "$1" in
  --domain)
    [ "$#" -ge 2 ] || {
      echo "--domain requires a value" >&2
      exit 2
    }
    DOMAIN="$2"
    shift 2
    ;;
  --real-ip-mode)  [ $# -ge 2 ] || { echo '--real-ip-mode requires direct|cloudflare' >&2; exit 2; }; REAL_IP_MODE=$2; shift 2
    ;;
  --skip-smoke)
    SKIP_SMOKE=1
    shift
    ;;
  --help | -h)
    usage
    exit 0
    ;;
  *)
    echo "Unknown argument: $1" >&2
    usage >&2
    exit 2
    ;;
  esac
done

if [ "$(id -u)" -eq 0 ]; then
  SUDO=""
else
  if ! sudo -n true 2>/dev/null; then
    echo "Run as root or as a user with passwordless sudo." >&2
    exit 1
  fi
  SUDO="sudo"
fi

if [ -z "$DOMAIN" ] && [ -r "$ENV_FILE" ]; then
  DOMAIN="$(sed -n 's/^DAR_DOMAIN=//p' "$ENV_FILE" | head -n 1)"
fi
if [ -z "$DOMAIN" ]; then
  echo 'DAR_DOMAIN (or --domain) is required.' >&2
  exit 2
fi
if [ "$REAL_IP_MODE" != "cloudflare" ] && [ "$REAL_IP_MODE" != "direct" ]; then
  echo "REAL_IP_MODE must be direct or cloudflare (got $REAL_IP_MODE)" >&2
  exit 2
fi
CERT_FILE="$CERT_ROOT/$DOMAIN/fullchain.pem"

render_tls_config() {
  cat <<'NGINX'
# Generated by deploy/setup-nginx.sh on __GENERATED_AT__.
# Certbot-managed TLS lines are preserved verbatim; do not edit by hand.
server {
    server_name __DOMAIN__;

    server_tokens off;
    client_max_body_size 12m;

    add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always;
    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;
    add_header X-Frame-Options "DENY" always;
    add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;

    location ^~ /.well-known/acme-challenge/ {
        root /var/www/certbot;
        default_type text/plain;
    }

    location /api/v1/ {
        proxy_pass http://127.0.0.1:5081;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Host $host;
        proxy_buffer_size 32k;
        proxy_buffers 8 32k;
        proxy_busy_buffers_size 64k;
        proxy_read_timeout 120s;
    }

    location / {
        proxy_pass http://127.0.0.1:5080;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Host $host;
        proxy_buffer_size 32k;
        proxy_buffers 8 32k;
        proxy_busy_buffers_size 64k;
        proxy_read_timeout 180s;
    }

    listen [::]:443 ssl ipv6only=on; # managed by Certbot
    listen 443 ssl; # managed by Certbot
    ssl_certificate /etc/letsencrypt/live/__DOMAIN__/fullchain.pem; # managed by Certbot
    ssl_certificate_key /etc/letsencrypt/live/__DOMAIN__/privkey.pem; # managed by Certbot
    include /etc/letsencrypt/options-ssl-nginx.conf; # managed by Certbot
    ssl_dhparam /etc/letsencrypt/ssl-dhparams.pem; # managed by Certbot
}

server {
    if ($host = __DOMAIN__) {
        return 301 https://$host$request_uri;
    }

    listen 80;
    listen [::]:80;
    server_name __DOMAIN__;
    return 404;
}
NGINX
}

render_http_config() {
  cat <<'NGINX'
# Generated by deploy/setup-nginx.sh on __GENERATED_AT__.
# HTTP-only block: no certificate exists yet. Certbot will add the TLS server.
server {
    listen 80;
    listen [::]:80;
    server_name __DOMAIN__;

    server_tokens off;
    client_max_body_size 12m;

    add_header X-Content-Type-Options "nosniff" always;
    add_header Referrer-Policy "strict-origin-when-cross-origin" always;
    add_header X-Frame-Options "DENY" always;
    add_header Permissions-Policy "camera=(), microphone=(), geolocation=()" always;

    location ^~ /.well-known/acme-challenge/ {
        root /var/www/certbot;
        default_type text/plain;
    }

    location /api/v1/ {
        proxy_pass http://127.0.0.1:5081;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Host $host;
        proxy_buffer_size 32k;
        proxy_buffers 8 32k;
        proxy_busy_buffers_size 64k;
        proxy_read_timeout 120s;
    }

    location / {
        proxy_pass http://127.0.0.1:5080;
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Forwarded-Proto https;
        proxy_set_header X-Forwarded-Host $host;
        proxy_buffer_size 32k;
        proxy_buffers 8 32k;
        proxy_busy_buffers_size 64k;
        proxy_read_timeout 180s;
    }
}
NGINX
}

wait_ready() {
  local url="$1"
  local args="$2"
  local deadline=$((SECONDS + 30))
  while [ "$SECONDS" -lt "$deadline" ]; do
    # shellcheck disable=SC2086
    if curl -fsS --max-time 5 $args "$url" >/dev/null 2>&1; then
      return 0
    fi
    sleep 2
  done
  return 1
}

echo "==> Certbot webroot"
$SUDO install -d -m 0755 -o www-data -g www-data /var/www/certbot

echo "==> Backup current site ($CONFIG_BACKUP_DIR)"
$SUDO install -d -m 0700 -o root -g root "$CONFIG_BACKUP_DIR"
if [ -f "$SITE_FILE" ]; then
  $SUDO install -m 0600 -o root -g root "$SITE_FILE" "$CONFIG_BACKUP_DIR/$SITE_NAME"
fi

TMP_FILE="$(mktemp)"
trap 'rm -f "$TMP_FILE"' EXIT

if [ -f "$CERT_FILE" ]; then
  echo "==> Certificate found for $DOMAIN: writing full TLS config"
  TLS_ENABLED=1
  render_tls_config | sed "s|__DOMAIN__|$DOMAIN|g; s|__GENERATED_AT__|$BACKUP_STAMP|g" >"$TMP_FILE"
else
  echo "==> No certificate for $DOMAIN yet: writing HTTP-only config for Certbot"
  TLS_ENABLED=0
  render_http_config | sed "s|__DOMAIN__|$DOMAIN|g; s|__GENERATED_AT__|$BACKUP_STAMP|g" >"$TMP_FILE"
fi

$SUDO install -m 0644 -o root -g root "$TMP_FILE" "$SITE_FILE"
$SUDO ln -sfn "$SITE_FILE" "$SITE_LINK"
$SUDO rm -f /etc/nginx/sites-enabled/default

# Cloudflare mode is a single setting: install the published-CF-range snippet so CF-Connecting-IP
# is accepted only from Cloudflare peers and $remote_addr becomes the real client IP.
if [ "$REAL_IP_MODE" = "cloudflare" ]; then
  echo "==> real-ip mode=cloudflare: install Cloudflare ranges snippet"
  $SUDO install -m 0644 -o root -g root "$SCRIPT_DIR/nginx/cloudflare-realip.conf" /etc/nginx/conf.d/00-dar-cloudflare-realip.conf
else
  echo "==> real-ip mode=direct: remove Cloudflare snippet (no proxy headers trusted)"
  $SUDO rm -f /etc/nginx/conf.d/00-dar-cloudflare-realip.conf
fi

echo "==> nginx -t"
if ! $SUDO nginx -t; then
  echo "nginx configuration test failed; restoring the previous site file." >&2
  if [ -f "$CONFIG_BACKUP_DIR/$SITE_NAME" ]; then
    $SUDO install -m 0644 -o root -g root "$CONFIG_BACKUP_DIR/$SITE_NAME" "$SITE_FILE"
    $SUDO nginx -t || true
  fi
  exit 1
fi

echo "==> Enable + reload nginx"
$SUDO systemctl enable nginx >/dev/null 2>&1 || true
if $SUDO systemctl is-active --quiet nginx; then
  $SUDO systemctl reload nginx
else
  $SUDO systemctl start nginx
fi

echo "==> Retired Docker Caddy (best effort, never fatal)"
if command -v docker >/dev/null 2>&1 && [ -f "$REPO_DIR/deploy/docker-compose.yml" ]; then
  (cd "$REPO_DIR" && $SUDO docker compose --env-file deploy/.env -f deploy/docker-compose.yml stop caddy >/dev/null 2>&1) || true
fi

if [ "$SKIP_SMOKE" -eq 1 ]; then
  echo "==> --skip-smoke: skipping local smoke requests"
else
  echo "==> Local smoke"
  if [ "$TLS_ENABLED" -eq 1 ]; then
    SMOKE_ARGS="-kfsS --resolve $DOMAIN:443:127.0.0.1"
    if wait_ready "https://$DOMAIN/health/ready" "$SMOKE_ARGS"; then
      echo "    https health ready: OK"
    else
      echo "    WARN: https://$DOMAIN/health/ready is not ready (services down or certificate mismatch)." >&2
    fi
    if wait_ready "https://$DOMAIN/api/v1/ping" "$SMOKE_ARGS"; then
      echo "    https api ping: OK"
    else
      echo "    WARN: https://$DOMAIN/api/v1/ping is not ready." >&2
    fi
  else
    if wait_ready "http://127.0.0.1/health/ready" "-fsS -H Host:$DOMAIN"; then
      echo "    http health ready: OK"
    else
      echo "    WARN: http health ready is not ready (services down)." >&2
    fi
  fi
fi

if [ "$TLS_ENABLED" -eq 0 ]; then
  echo "==> Next step: issue the certificate with Certbot:"
  echo "    sudo certbot --nginx -d $DOMAIN --non-interactive --agree-tos -m admin@rigxhardware.com --redirect"
fi

echo "NGINX_OK domain=$DOMAIN tls=$TLS_ENABLED"
